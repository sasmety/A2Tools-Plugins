def read(name):
    return open(os.path.join(ROOT, "pet-souls", name), encoding="utf-8").read()


def js_object(text, name):
    """The JSON object literal assigned to `const <name>` (keys may be bare numbers or words)."""
    body = re.search(r"const %s = (\{.*?\n\});" % name, text, re.S).group(1)
    return json.loads(re.sub(r"^(\s*)([\w-]+):", r'\1"\2":', body, flags=re.M))


def other_languages(names):
    """English, and only the languages whose text differs from it."""
    return {"en": names["en"], **{k: v for k, v in sorted(names.items()) if k != "en" and v and v != names["en"]}}


