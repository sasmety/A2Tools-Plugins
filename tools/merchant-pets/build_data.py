sources_js = read("sources.js")
sources = js_object(sources_js, "PET_SOURCES")
source_text = js_object(sources_js, "SOURCE_TEXT")

pets, regions = {}, {}
for pet in sorted(set(ITEMS.values())):
    found = {}
    for drop in sources.get(str(pet), {}).get("drops", []):
        region = drop.get("region")
        if not region:
            continue
        regions.setdefault(region, drop["map"])
        r = found.setdefault(region, [region, 0, 0])
        r[1] += drop.get("spawns", 0)
        r[2] = max(r[2], float(drop["chance"].rstrip("%")))
    drops = sorted(found.values(), key=lambda r: -r[1])
    for r in drops:
        r[2] = int(r[2]) if r[2] == int(r[2]) else r[2]
    pets[pet] = [genus.get(str(pet), ""), drops]

